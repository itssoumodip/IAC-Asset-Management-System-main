"""Finance register rows → SQL, one plan CSV per category (desktops, laptops, CCTV…).

Usage:  python -I "import sql/register_import.py" "import sql/register-desktops-plan.csv"
Writes register-desktops-import.sql next to the plan. Run it with psql; it refuses to run twice.

Plan CSV columns (one row per register row; edit it, then regenerate):
  action        new  = create the asset (numbered from the owning team's counter)
                fill = it is already in the software: add the register's details where blank
                skip = leave it out
  asset_codes   for fill: the existing Asset ID(s), separated by spaces (a register row that
                covers two machines lists both)
  register_row, item, unit_cost, purchase_date, capitalised, bill, party   from the register
  team          IT / ADM / PRJ (who owns it; default IT)
  category, subcategory, description, model, serial    what to create
  status, condition   for new: e.g. In Use / Good, In Store / Unknown, Broken / Not Working
  location_code       a location code in the software (blank = none)
  holder              exact name of the person who has it (they get it with "not yet confirmed";
                      no email or notification is sent); blank = nobody
  note                kept in the asset's remarks

What it never does: overwrite a value already in the software, send notifications, or touch
anything not listed in the plan. Every created or filled asset gets an audit entry.
"""
import csv, json, os, sys

def q(v):
    if v is None or v == '': return 'NULL'
    return "'" + str(v).replace("'", "''") + "'"

def money(v):
    return repr(round(float(v), 2)) if v not in (None, '') else 'NULL'

def day(v):
    return f"DATE '{v}'" if v else 'NULL'

def main():
    plan = sys.argv[1]
    name = os.path.basename(plan).replace('-plan.csv', '')
    tag = name                       # e.g. register-desktops
    rows = list(csv.DictReader(open(plan, encoding='utf-8-sig')))
    vals = []
    for n, r in enumerate(rows, start=1):
        r = {k: (v or '').strip() for k, v in r.items()}
        act = r['action'].lower()
        if act not in ('new', 'fill', 'skip'): raise SystemExit(f'plan row {n}: action must be new, fill or skip')
        if act == 'skip': continue
        codes = r['asset_codes'].split()
        if act == 'fill' and not codes: raise SystemExit(f'plan row {n}: fill needs asset_codes')
        if act == 'new' and codes: raise SystemExit(f'plan row {n}: new must not have asset_codes')
        # "Unknown" is a switched-off condition in the software, so new rows must say.
        if act == 'new' and r['condition'] not in ('New', 'Excellent', 'Good', 'Fair', 'Poor', 'Damaged', 'Not Working'):
            raise SystemExit(f'plan row {n}: condition must be New, Excellent, Good, Fair, Poor, Damaged or Not Working')
        meta = {k: v for k, v in {
            'row': int(r['register_row']), 'item': r['item'], 'unitCost': float(r['unit_cost']) if r['unit_cost'] else None,
            'purchaseDate': r['purchase_date'] or None, 'capitalised': r['capitalised'] or None, 'bill': r['bill'] or None,
            'party': r['party'] or None, 'custodian': r.get('register_custodian') or None, 'location': r.get('register_location') or None,
        }.items() if v is not None}
        # A row covering several machines splits its cost evenly for blanks.
        share = float(r['unit_cost']) / len(codes) if codes and r['unit_cost'] else (float(r['unit_cost']) if r['unit_cost'] else None)
        targets = codes or [None]
        for code in targets:
            vals.append('  (' + ', '.join([
                str(len(vals) + 1), q(act), q(code), q(r.get('team') or 'IT'), q(r['category']), q(r['subcategory']),
                q(r['description']), q(r['model']), q(r['serial']), money(share), day(r['purchase_date']),
                day(r['capitalised']), q(r['bill']), q(r['party']), q(r['status'] or 'In Store'),
                q(r['condition'] or 'Unknown'), q(r['location_code']), q(r['holder']), q(r['note']),
                q(json.dumps(meta, ensure_ascii=False)) + '::jsonb',
            ]) + ')')
    L = [
        f'-- Finance register import: {name}. Generated by register_import.py from {os.path.basename(plan)}.',
        '-- "fill" rows add the register cost, dates, bill and party to existing assets where blank.',
        '-- "new" rows create the asset; a named holder gets it as "not yet confirmed". No emails or notifications.',
        '-- Refuses to run twice.',
        '\\set ON_ERROR_STOP on',
        'BEGIN;',
        'DO $$ BEGIN',
        f"  IF EXISTS (SELECT 1 FROM audit_events WHERE action = 'REGISTER_IMPORTED' AND changes->>'tag' = '{tag}') THEN",
        f"    RAISE EXCEPTION '{name} was already imported.';",
        '  END IF;',
        'END $$;',
        'CREATE TEMP TABLE importer ON COMMIT DROP AS',
        "  SELECT ur.user_id AS id FROM user_roles ur WHERE ur.role_code='SUPER_ADMIN' ORDER BY ur.granted_at LIMIT 1;",
        'CREATE TEMP TABLE reg (n int PRIMARY KEY, action text, asset_code text, team text, category text, asset_type text,',
        '  description text, model text, serial text, cost numeric, bought date, capitalised date, bill text, party text,',
        '  status text, condition text, location_code text, holder text, note text, meta jsonb, asset_id uuid, holder_id uuid) ON COMMIT DROP;',
        'INSERT INTO reg (n, action, asset_code, team, category, asset_type, description, model, serial, cost, bought, capitalised,',
        '  bill, party, status, condition, location_code, holder, note, meta) VALUES',
        ',\n'.join(vals) + ';',
        '',
        '-- Check everything first: existing assets, people, locations, teams.',
        "UPDATE reg SET asset_id = a.id FROM assets a WHERE reg.action = 'fill' AND a.asset_code = reg.asset_code AND a.removed_at IS NULL;",
        "UPDATE reg SET holder_id = (SELECT u.id FROM users u WHERE lower(u.display_name) = lower(reg.holder)",
        "  AND u.merged_into_user_id IS NULL AND u.left_at IS NULL) WHERE reg.holder IS NOT NULL;",
        'DO $$ DECLARE r record; BEGIN',
        "  FOR r IN SELECT n, asset_code FROM reg WHERE action = 'fill' AND asset_id IS NULL LOOP",
        "    RAISE EXCEPTION 'Row %: asset % is not in the software.', r.n, r.asset_code; END LOOP;",
        '  FOR r IN SELECT n, holder FROM reg WHERE holder IS NOT NULL AND holder_id IS NULL LOOP',
        "    RAISE EXCEPTION 'Row %: no current staff member is called %.', r.n, r.holder; END LOOP;",
        '  FOR r IN SELECT n, location_code FROM reg WHERE location_code IS NOT NULL',
        '      AND NOT EXISTS (SELECT 1 FROM locations l WHERE l.code = reg.location_code AND l.active) LOOP',
        "    RAISE EXCEPTION 'Row %: location % does not exist.', r.n, r.location_code; END LOOP;",
        '  FOR r IN SELECT n, team FROM reg WHERE NOT EXISTS (SELECT 1 FROM teams t WHERE t.code = reg.team) LOOP',
        "    RAISE EXCEPTION 'Row %: team % does not exist.', r.n, r.team; END LOOP;",
        "  FOR r IN SELECT n, serial FROM reg WHERE action = 'new' AND serial IS NOT NULL",
        '      AND EXISTS (SELECT 1 FROM assets a WHERE lower(a.serial_number) = lower(reg.serial) AND a.removed_at IS NULL) LOOP',
        "    RAISE EXCEPTION 'Row %: serial % is already in the software; use fill.', r.n, r.serial; END LOOP;",
        'END $$;',
        '',
        '-- Existing assets: blanks only. The register row is recorded on the asset either way.',
        'UPDATE assets a SET',
        '  purchase_cost = coalesce(a.purchase_cost, reg.cost),',
        '  purchase_date = coalesce(a.purchase_date, reg.bought),',
        '  capitalisation_date = coalesce(a.capitalisation_date, reg.capitalised),',
        "  invoice_number = coalesce(nullif(btrim(a.invoice_number), ''), reg.bill),",
        "  supplier = coalesce(nullif(btrim(a.supplier), ''), reg.party),",
        "  legacy_metadata = coalesce(a.legacy_metadata, '{}'::jsonb) || jsonb_build_object('financeRegister', reg.meta),",
        '  version = a.version + 1, updated_at = now()',
        "FROM reg WHERE reg.action = 'fill' AND a.id = reg.asset_id;",
        '',
        '-- New assets, numbered from the owning team\'s counter.',
        "SELECT pg_advisory_xact_lock(hashtextextended('iac-asset-sequence', 0));",
        'DO $$ DECLARE r record; nxt bigint; prefix text; acode text; tid uuid; aid uuid; BEGIN',
        "  FOR r IN SELECT * FROM reg WHERE action = 'new' ORDER BY n LOOP",
        '    SELECT id INTO tid FROM teams WHERE code = r.team;',
        '    SELECT k.next_value, t.asset_code_prefix INTO nxt, prefix FROM team_asset_counters k JOIN teams t ON t.id = k.team_id',
        '     WHERE k.team_id = tid FOR UPDATE OF k;',
        "    LOOP acode := 'IAC-' || prefix || '-' || lpad(nxt::text, 6, '0');",
        '      EXIT WHEN NOT EXISTS (SELECT 1 FROM assets WHERE asset_code = acode); nxt := nxt + 1; END LOOP;',
        '    UPDATE team_asset_counters SET next_value = nxt + 1 WHERE team_id = tid;',
        '    INSERT INTO assets(asset_code, category, asset_type, description, model, serial_number, ownership_type, status, condition,',
        '      risk_level, owning_team_id, location_id, purchase_date, purchase_cost, currency, invoice_number, supplier,',
        '      capitalisation_date, finance_pending, finance_status, remarks, legacy_metadata, created_by)',
        "    VALUES (acode, r.category, r.asset_type, r.description, r.model, r.serial, 'Owned', r.status, r.condition, 'Low', tid,",
        '      (SELECT id FROM locations WHERE code = r.location_code), r.bought, r.cost, \'INR\', r.bill, r.party, r.capitalised,',
        "      true, 'PENDING', nullif(concat_ws(' ', 'From the finance register (row ' || (r.meta->>'row') || ').', r.note), ''),",
        "      jsonb_build_object('financeRegister', r.meta), (SELECT id FROM importer))",
        '    RETURNING id INTO aid;',
        '    UPDATE reg SET asset_id = aid, asset_code = acode WHERE n = r.n;',
        '  END LOOP;',
        'END $$;',
        '',
        '-- Named holders get the asset, waiting for them to confirm. Nothing is sent to them.',
        "INSERT INTO assignments(asset_id, user_id, assigned_by, acknowledgement, handover_note)",
        "SELECT reg.asset_id, reg.holder_id, (SELECT id FROM importer), 'PENDING', 'Recorded from the finance register.'",
        "  FROM reg WHERE reg.action = 'new' AND reg.holder_id IS NOT NULL;",
        '',
        'INSERT INTO audit_events(actor_id, actor_kind, entity_type, entity_id, action, changes, request_id)',
        "SELECT (SELECT id FROM importer), 'USER', 'asset', reg.asset_id,",
        "       CASE WHEN reg.action = 'new' THEN 'ASSET_CREATED' ELSE 'ASSET_UPDATED' END,",
        "       jsonb_build_object('source', 'Finance register', 'registerRow', reg.meta->>'row', 'assetCode', reg.asset_code), gen_random_uuid()",
        '  FROM reg;',
        'INSERT INTO audit_events(actor_id, actor_kind, entity_type, entity_id, action, changes, request_id)',
        f"SELECT (SELECT id FROM importer), 'USER', 'import', NULL, 'REGISTER_IMPORTED', jsonb_build_object('tag', '{tag}',",
        "  'filled', (SELECT count(*) FROM reg WHERE action = 'fill'), 'created', (SELECT count(*) FROM reg WHERE action = 'new')), gen_random_uuid();",
        'DO $$ DECLARE r record; BEGIN',
        "  RAISE NOTICE 'Filled: %, created: %', (SELECT count(*) FROM reg WHERE action = 'fill'), (SELECT count(*) FROM reg WHERE action = 'new');",
        "  FOR r IN SELECT n, action, asset_code, description, holder FROM reg ORDER BY n LOOP",
        "    RAISE NOTICE '% % % %', r.action, r.asset_code, r.description, coalesce('-> ' || r.holder, '');",
        '  END LOOP;',
        'END $$;',
        'COMMIT;',
    ]
    out = os.path.join(os.path.dirname(os.path.abspath(plan)), f'{name}-import.sql')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print(f'{len(vals)} rows -> {out}')

if __name__ == '__main__':
    main()
